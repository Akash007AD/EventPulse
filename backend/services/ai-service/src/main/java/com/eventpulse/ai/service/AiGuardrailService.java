package com.eventpulse.ai.service;

import java.util.Optional;

public interface AiGuardrailService {

    /**
     * Inspects a user query for prompt injection, policy violations, or company exploitation attempts.
     * @param query the raw user query
     * @return Optional containing a safe refusal response if blocked, or empty if safe.
     */
    Optional<String> validateAndFilter(String query);

    /**
     * Inspects model-generated output to prevent hallucinated discounts, leaked secrets,
     * or unauthorized commitments before returning to the user.
     * @param generatedOutput the text generated by the model
     * @return Optional containing a safe fallback if output violated safety rules, or empty if safe.
     */
    Optional<String> validateOutput(String generatedOutput);

    /**
     * Encloses untrusted user input within quarantine XML delimiters to prevent prompt injection hijacking.
     * @param rawQuery user text
     * @return delimited prompt segment
     */
    String quarantinePrompt(String rawQuery);
}
